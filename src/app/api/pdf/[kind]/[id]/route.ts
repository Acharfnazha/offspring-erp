import { prisma } from "@/lib/db";
import { getCurrentUser } from "@/lib/auth/session";
import { hasPermission } from "@/lib/auth/permissions";
import { renderPdf, pdfResponse, type PdfDoc } from "@/lib/pdf";
import { D, formatKg, formatMoney, sum } from "@/lib/money";
import { formatDate, isoDate } from "@/lib/dates";
import { label } from "@/lib/schemas";
import { getSetting } from "@/lib/options";

export const dynamic = "force-dynamic";

type Company = PdfDoc["company"];
const DISCLAIMER = "Generated by OFFSPRING ERP. Trade and shipping documents require review by authorized personnel; this document does not by itself certify legal, customs or phytosanitary compliance.";

export async function GET(req: Request, { params }: { params: Promise<{ kind: string; id: string }> }) {
  const user = await getCurrentUser();
  if (!user) return new Response("Unauthorized", { status: 401 });
  const { kind, id } = await params;
  const url = new URL(req.url);
  const download = url.searchParams.get("download") === "1";
  const company = await getSetting<Company>("company", { name: "Offspring Group S.A.R.L.", address: "Lebanon" });
  const m = (v: unknown, c: string) => formatMoney(v as string, c);

  if (kind === "quotation") {
    if (!hasPermission(user.role, "quotations:read")) return new Response("Forbidden", { status: 403 });
    const q = await prisma.quotation.findUnique({ where: { id }, include: { customer: true, items: { orderBy: { sortOrder: "asc" } } } });
    if (!q) return new Response("Not found", { status: 404 });
    const bytes = await renderPdf({
      title: "QUOTATION", number: `${q.quoteNo}  |  Rev. ${q.revision}`, company, watermark: q.status === "DRAFT" ? "DRAFT" : undefined,
      meta: [["Issue date", formatDate(q.issueDate)], ["Valid until", formatDate(q.validUntil)], ["Currency", q.currency], ["Incoterm (2020)", `${q.incoterm}${q.portOfDischarge && ["CFR", "CIF", "CPT", "CIP", "DAP", "DDP"].includes(q.incoterm) ? ` ${q.portOfDischarge}` : q.portOfLoading ? ` ${q.portOfLoading}` : ""}`], ["Port of loading", q.portOfLoading ?? "-"], ["Port of discharge", q.portOfDischarge ?? "-"]],
      parties: [
        { title: "Prepared for", lines: [q.customer.companyName, q.customer.contactPerson, q.customer.address, [q.customer.city, q.customer.country].filter(Boolean).join(", "), q.customer.email] },
        { title: "Offer", lines: [`Payment: ${q.paymentTerms ?? "To be agreed"}`, q.deliveryTerms ? `Delivery: ${q.deliveryTerms}` : null, q.shipmentDetails] },
      ],
      table: {
        columns: [{ header: "Product", width: 30 }, { header: "Grade", width: 9 }, { header: "Origin", width: 9 }, { header: "Packaging", width: 13 }, { header: "Quantity", width: 12, align: "right" }, { header: `Price/kg`, width: 11, align: "right" }, { header: "Amount", width: 14, align: "right" }],
        rows: q.items.map((i) => [i.description + (Number(i.discountPct) > 0 ? ` (-${i.discountPct}%)` : ""), label(i.grade), i.origin, i.packaging ?? "-", formatKg(i.quantityKg), m(i.unitPrice, q.currency), m(i.lineTotal, q.currency)]),
      },
      totals: [["Subtotal", m(q.subtotal, q.currency)], ["Discounts", `-${m(q.discountTotal, q.currency)}`], [`Total ${q.incoterm}`, m(q.total, q.currency), true]],
      sections: [
        ...(q.notes ? [{ title: "Notes", body: q.notes }] : []),
        { title: "Conditions", body: `Prices are quoted ${q.incoterm} (Incoterms 2020). ${["EXW", "FCA", "FOB"].includes(q.incoterm) ? "Main carriage freight and insurance are NOT included." : q.incoterm === "CFR" || q.incoterm === "CPT" ? "Freight to the named destination is included; cargo insurance is NOT included." : "Freight and minimum cargo insurance to the named destination are included as per the Incoterm."} Offer subject to availability at time of order confirmation and valid until ${formatDate(q.validUntil)}. Quantities are net fruit weight in kilograms.` },
      ],
      footer: DISCLAIMER,
    });
    return pdfResponse(bytes, `${q.quoteNo}-r${q.revision}.pdf`, download);
  }

  if (kind === "invoice") {
    if (!hasPermission(user.role, "finance:read")) return new Response("Forbidden", { status: 403 });
    const inv = await prisma.invoice.findUnique({ where: { id }, include: { customer: true, supplier: true, items: { orderBy: { sortOrder: "asc" } }, salesOrder: true, shipment: true, originalInvoice: true, storageContract: true } });
    if (!inv) return new Response("Not found", { status: 404 });
    const party = inv.customer ?? inv.supplier;
    const title = { SALES: "COMMERCIAL INVOICE", PURCHASE: "PURCHASE INVOICE", COLD_STORAGE: "STORAGE INVOICE", PRO_FORMA: "PRO FORMA INVOICE", CREDIT_NOTE: "CREDIT NOTE" }[inv.type];
    const balance = D(inv.total).minus(D(inv.amountPaid));
    const bytes = await renderPdf({
      title, number: inv.invoiceNo, company, watermark: inv.status === "DRAFT" ? "DRAFT" : inv.status === "CANCELLED" ? "CANCELLED" : inv.status === "PAID" ? "PAID" : undefined,
      meta: [["Issue date", formatDate(inv.issueDate)], ["Due date", formatDate(inv.dueDate)], ["Currency", inv.currency], ["Status", label(inv.status)], ["Reference", inv.salesOrder?.orderNo ?? inv.storageContract?.contractNo ?? inv.originalInvoice?.invoiceNo ?? "-"], ["Incoterm", inv.incoterm ?? "-"]],
      parties: [
        { title: inv.type === "PURCHASE" ? "Supplier" : "Bill to", lines: [inv.customer?.companyName ?? inv.supplier?.name, party?.address, [party?.city, party?.country].filter(Boolean).join(", "), party?.email] },
        ...(inv.shipment ? [{ title: "Shipment", lines: [inv.shipment.shipmentNo, inv.shipment.containerNo ? `Container ${inv.shipment.containerNo}` : null, `${inv.shipment.portOfLoading ?? ""} -> ${inv.shipment.portOfDischarge ?? ""}`, inv.shipment.shippingLine] }] : []),
      ],
      table: {
        columns: [{ header: "Description", width: 40 }, { header: "Qty", width: 12, align: "right" }, { header: "Unit", width: 8 }, { header: "Unit price", width: 12, align: "right" }, { header: "Disc/Tax", width: 10, align: "right" }, { header: "Amount", width: 14, align: "right" }],
        rows: inv.items.map((i) => [i.description, D(i.quantity).toFixed(i.unit === "kg" || i.unit === "kg-month" ? 1 : 2), i.unit, m(i.unitPrice, inv.currency), `${Number(i.discountPct) ? `-${i.discountPct}%` : ""}${Number(i.taxPct) ? ` +${i.taxPct}%` : ""}` || "-", m(i.lineTotal, inv.currency)]),
      },
      totals: [["Subtotal", m(inv.subtotal, inv.currency)], ["Discounts", `-${m(inv.discountTotal, inv.currency)}`], ["Tax", m(inv.taxTotal, inv.currency)], ["Total", m(inv.total, inv.currency), true], ["Paid / credited", `-${m(inv.amountPaid, inv.currency)}`], ["Balance due", m(balance, inv.currency), true]],
      sections: [...(inv.notes ? [{ title: "Notes", body: inv.notes }] : []), ...(company.bank ? [{ title: "Payment instructions", body: company.bank }] : []), ...(inv.type === "PRO_FORMA" ? [{ title: "Pro forma", body: "This pro forma invoice is not a demand for payment and is issued for advance payment / import licensing purposes only." }] : [])],
      footer: DISCLAIMER,
    });
    return pdfResponse(bytes, `${inv.invoiceNo}.pdf`, download);
  }

  if (kind === "receipt") {
    if (!hasPermission(user.role, "finance:read")) return new Response("Forbidden", { status: 403 });
    const p = await prisma.payment.findUnique({ where: { id }, include: { customer: true, supplier: true, allocations: { include: { invoice: true } } } });
    if (!p) return new Response("Not found", { status: 404 });
    const alloc = sum(p.allocations.map((a) => a.amount));
    const bytes = await renderPdf({
      title: p.direction === "INCOMING" ? "PAYMENT RECEIPT" : "PAYMENT VOUCHER", number: p.paymentNo, company, watermark: p.voidedAt ? "VOID" : undefined,
      meta: [["Date", formatDate(p.paidAt)], ["Method", label(p.method)], ["Reference", p.reference ?? "-"], ["Currency", p.currency], ["Amount", m(p.amount, p.currency)], ["Status", p.voidedAt ? "Voided" : "Posted"]],
      parties: [{ title: p.direction === "INCOMING" ? "Received from" : "Paid to", lines: [p.customer?.companyName ?? p.supplier?.name, p.customer?.country ?? p.supplier?.country] }],
      table: { columns: [{ header: "Invoice", width: 30 }, { header: "Issue date", width: 20 }, { header: "Invoice total", width: 25, align: "right" }, { header: "Allocated", width: 25, align: "right" }], rows: p.allocations.map((a) => [a.invoice.invoiceNo, formatDate(a.invoice.issueDate), m(a.invoice.total, a.invoice.currency), m(a.amount, p.currency)]) },
      totals: [["Allocated to invoices", m(alloc, p.currency)], ["Unallocated (on account)", m(D(p.amount).minus(alloc), p.currency)], ["Payment amount", m(p.amount, p.currency), true]],
      sections: p.notes ? [{ title: "Notes", body: p.notes }] : [],
    });
    return pdfResponse(bytes, `${p.paymentNo}.pdf`, download);
  }

  if (kind === "statement") {
    if (!hasPermission(user.role, "finance:read")) return new Response("Forbidden", { status: 403 });
    const supplier = url.searchParams.get("party") === "supplier";
    const party = supplier ? await prisma.supplier.findUnique({ where: { id } }) : await prisma.customer.findUnique({ where: { id } });
    if (!party) return new Response("Not found", { status: 404 });
    const where = supplier ? { supplierId: id } : { customerId: id };
    const [invoices, payments] = await Promise.all([
      prisma.invoice.findMany({ where: { ...where, status: { notIn: ["DRAFT", "CANCELLED"] }, type: { not: "PRO_FORMA" } }, orderBy: { issueDate: "asc" } }),
      prisma.payment.findMany({ where: { ...where, voidedAt: null }, orderBy: { paidAt: "asc" } }),
    ]);
    type Entry = { date: Date; doc: string; desc: string; debit: string; credit: string };
    const entries: Entry[] = [
      ...invoices.map((i) => (i.type === "CREDIT_NOTE" ? { date: i.issueDate, doc: i.invoiceNo, desc: "Credit note", debit: "0", credit: i.total.toString() } : { date: i.issueDate, doc: i.invoiceNo, desc: label(i.type) + " invoice", debit: i.total.toString(), credit: "0" })),
      ...payments.map((p) => ({ date: p.paidAt, doc: p.paymentNo, desc: `Payment (${label(p.method)})${p.reference ? ` ${p.reference}` : ""}`, debit: "0", credit: p.amount.toString() })),
    ].sort((a, b) => a.date.getTime() - b.date.getTime());
    let bal = D(0);
    const rows = entries.map((e) => { bal = bal.plus(e.debit).minus(e.credit); return [isoDate(e.date), e.doc, e.desc, D(e.debit).gt(0) ? m(e.debit, "USD") : "", D(e.credit).gt(0) ? m(e.credit, "USD") : "", m(bal, "USD")]; });
    const name = "companyName" in party ? party.companyName : party.name;
    const bytes = await renderPdf({
      title: "ACCOUNT STATEMENT", number: `${party.code} | ${isoDate(new Date())}`, company,
      meta: [["Account", name], ["Statement date", formatDate(new Date())], ["Currency", "USD (as invoiced)"]],
      parties: [{ title: supplier ? "Supplier" : "Customer", lines: [name, party.address, [party.city, party.country].filter(Boolean).join(", ")] }],
      table: { columns: [{ header: "Date", width: 12 }, { header: "Document", width: 18 }, { header: "Description", width: 30 }, { header: supplier ? "Billed" : "Debit", width: 13, align: "right" }, { header: supplier ? "Paid" : "Credit", width: 13, align: "right" }, { header: "Balance", width: 14, align: "right" }], rows },
      totals: [[supplier ? "Balance owed to supplier" : "Balance due (incl. unallocated credits)", m(bal, "USD"), true]],
      sections: [{ title: "Note", body: "Multi-currency documents are listed at their face value. Please report discrepancies within 15 days." }],
    });
    return pdfResponse(bytes, `statement-${party.code}.pdf`, download);
  }

  return new Response("Unknown document", { status: 404 });
}
